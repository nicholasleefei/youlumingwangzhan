export function getCountryDisplayName(code: string, locale: string = "zh"): string {
  const country = COUNTRY_LIST.find((c) => c.code === code || c.nameEn.toLowerCase() === code.toLowerCase());
  if (!country) return code;
  return locale === "zh" ? `${country.nameZh} / ${country.nameEn}` : `${country.nameEn} / ${country.nameZh}`;
}

export function matchCountryByName(name: string): CountryOption | null {
  const lower = name.toLowerCase().trim();
  for (const c of COUNTRY_LIST) {
    if (
      c.code.toLowerCase() === lower ||
      c.nameEn.toLowerCase() === lower ||
      c.nameZh === lower ||
      c.nameEn.toLowerCase().includes(lower) ||
      c.nameZh.includes(lower)
    ) {
      return c;
    }
  }
  return null;
}